#!/usr/bin/env bash
# ============================================================
# lib/utils.sh — 공통 유틸리티 라이브러리
#
# 역할:
#   모든 Bash 모듈과 진입점에서 공통으로 사용하는 함수들을 제공합니다.
#   - 색상 로그 출력 (OK=초록, WARNING=노랑, CRITICAL=빨강)
#   - JSON 이스케이프 처리 (Bash → Python 파이프 시 파싱 오류 방지)
#   - Audit 로그 기록 (누가, 언제, 어떤 액션을 했는지 추적)
#   - 이력 파일 자동 로테이션 (최근 5개만 유지)
# ============================================================

# ── ANSI 색상 코드 ─────────────────────────────────────────
RED='\033[0;31m'
YELLOW='\033[1;33m'
GREEN='\033[0;32m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'   # No Color (색상 초기화)


# ────────────────────────────────────────────────────────────
# 색상 로그 출력 함수
#
# 상태별로 색상을 구분하여 터미널에서 빠르게 식별할 수 있도록 합니다.
# Python 분석 엔진 실행 전(Bash 초기화 단계)에도 사용됩니다.
# ────────────────────────────────────────────────────────────
log_ok()   { echo -e "${GREEN}[OK]${NC}      $*" >&2; }
log_warn() { echo -e "${YELLOW}[WARNING]${NC} $*" >&2; }
log_crit() { echo -e "${RED}[CRITICAL]${NC} $*" >&2; }
log_info() { echo -e "${CYAN}[INFO]${NC}    $*" >&2; }
log_err()  { echo -e "${RED}[ERROR]${NC}   $*" >&2; }  # stderr로 출력 (stdout과 구분)


# ────────────────────────────────────────────────────────────
# audit_log: 감사(Audit) 로그 기록
#
# 누가 언제 어떤 작업을 했는지 기록합니다.
# --fix 자동 복구 액션도 여기에 기록되어 나중에 추적 가능합니다.
#
# 출력 예:
#   [2026-04-22 20:30:01] run executed | role=default | fix=false
#   [2026-04-22 20:31:15] [FIX] TMOUT 설정 완료
# ────────────────────────────────────────────────────────────
AUDIT_LOG="${SCRIPT_DIR}/logs/audit.log"
audit_log() {
    mkdir -p "$(dirname "$AUDIT_LOG")"
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*" >> "$AUDIT_LOG"
}


# ────────────────────────────────────────────────────────────
# json_escape: 문자열을 JSON 안전 값으로 변환
#
# 왜 필요한가?
#   Bash에서 수집한 값(예: df 출력, 보안 설정 문자열)에
#   쌍따옴표(")나 줄바꿈(\n)이 포함되면 Python의 json.loads()에서
#   파싱 에러가 발생합니다.
#   이 함수는 printf로 JSON을 조립하기 전에 값을 안전하게 정제합니다.
#
# 처리 순서:
#   1. 역슬래시(\) 먼저 이스케이프 (순서 중요!)
#   2. 쌍따옴표(") → \"
#   3. 줄바꿈(\n), 캐리지 리턴(\r), 탭(\t) → 공백으로 치환
# ────────────────────────────────────────────────────────────
json_escape() {
    local val="$1"
    val="${val//\\/\\\\}"     # 역슬래시 먼저 처리 (이 순서를 바꾸면 이중 이스케이프 발생)
    val="${val//\"/\\\"}"     # 쌍따옴표 이스케이프
    val="${val//$'\n'/ }"     # 줄바꿈 → 공백
    val="${val//$'\r'/ }"     # CR 제거
    val="${val//$'\t'/ }"     # 탭 → 공백
    printf '%s' "$val"
}


# ────────────────────────────────────────────────────────────
# history_rotate: 이력 JSON 파일 자동 로테이션
#
# Trend 분석을 위해 최근 5개의 실행 결과를 보관합니다.
# 6번째부터는 가장 오래된 파일을 자동 삭제합니다.
# 디스크가 이력 파일로 채워지는 것을 방지합니다.
# ────────────────────────────────────────────────────────────
history_rotate() {
    local history_dir="${SCRIPT_DIR}/reports/history"
    mkdir -p "$history_dir"

    local count
    count=$(ls -1 "$history_dir"/*.json 2>/dev/null | wc -l)

    # 5개 초과 시 오래된 것부터 삭제
    if [[ "$count" -ge 5 ]]; then
        ls -t "$history_dir"/*.json 2>/dev/null | tail -n +6 | xargs -r rm -f
    fi
}
